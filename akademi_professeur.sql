create or replace function public.professor_create_student(p_professor_code text,p_student_code text,p_name text,p_phone text,p_course_slug text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare p public.academy_professors%rowtype; sid bigint; cid bigint;
begin
 select * into p from public.academy_professors where active and crypt(p_professor_code,access_code_hash)=access_code_hash limit 1;
 if not found then return jsonb_build_object('ok',false,'message','Kòd pwofesè a pa valab.'); end if;
 if exists(select 1 from public.students where code=trim(p_student_code)) then return jsonb_build_object('ok',false,'message','Kòd elèv sa deja egziste.'); end if;
 select id into cid from public.courses where slug=p_course_slug;
 if cid is null then return jsonb_build_object('ok',false,'message','Kou a pa egziste.'); end if;
 insert into public.students(code,nom,telephone,created_by_professor_id) values(trim(p_student_code),trim(p_name),nullif(trim(p_phone),''),p.id) returning id into sid;
 insert into public.student_courses(student_id,course_id) values(sid,cid);
 return jsonb_build_object('ok',true,'message','Elèv kreye.');
end $$;

