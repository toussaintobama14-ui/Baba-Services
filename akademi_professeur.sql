create extension if not exists pgcrypto;

create table if not exists public.academy_professors (
 id bigint generated by default as identity primary key,
 full_name text not null,
 phone text,
 access_code_hash text not null,
 active boolean not null default true,
 created_at timestamptz not null default now()
);

alter table public.courses add column if not exists professor_id bigint references public.academy_professors(id) on delete set null;
alter table public.courses add column if not exists price_htg integer not null default 250;
alter table public.students add column if not exists created_by_professor_id bigint references public.academy_professors(id) on delete set null;
alter table public.student_assignments add column if not exists professor_id bigint references public.academy_professors(id) on delete set null;

create table if not exists public.professor_sales (
 id bigint generated by default as identity primary key,
 professor_id bigint not null references public.academy_professors(id) on delete restrict,
 student_code text not null,
 course_slug text not null,
 sale_price_htg integer not null check(sale_price_htg>0),
 academy_share_htg integer generated always as (round(sale_price_htg*0.25)::integer) stored,
 professor_share_htg integer generated always as (sale_price_htg-round(sale_price_htg*0.25)::integer) stored,
 payment_status text not null default 'collected' check(payment_status in ('collected','pending','paid_to_professor')),
 created_at timestamptz not null default now()
);
create table if not exists public.professor_messages (
 id bigint generated by default as identity primary key,
 professor_id bigint not null references public.academy_professors(id) on delete cascade,
 message text not null,
 sender_role text not null check(sender_role in ('professor','admin')),
 created_at timestamptz not null default now()
);
create table if not exists public.professor_certificate_requests (
 id bigint generated by default as identity primary key,
 professor_id bigint not null references public.academy_professors(id) on delete cascade,
 student_code text not null,
 course_slug text not null,
 note text,
 status text not null default 'pending' check(status in ('pending','approved','refused')),
 created_at timestamptz not null default now()
);

create or replace function public._academy_admin_ok(p_code text)
returns boolean language sql security definer set search_path=public
as $$
 select exists(select 1 from public.admins a where crypt(p_code,a.code_hash)=a.code_hash);
$$;

create or replace function public.professor_login(p_code text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare p public.academy_professors%rowtype;
begin
 select * into p from public.academy_professors where active and crypt(p_code,access_code_hash)=access_code_hash limit 1;
 if not found then return jsonb_build_object('ok',false,'message','Kòd pwofesè a pa kòrèk.'); end if;
 return jsonb_build_object('ok',true,'id',p.id,'name',p.full_name);
end $$;

create or replace function public.admin_create_professor(p_admin_code text,p_name text,p_phone text,p_professor_code text)
returns jsonb language plpgsql security definer set search_path=public
as $$
begin
 if not public._academy_admin_ok(p_admin_code) then return jsonb_build_object('ok',false,'message','Kòd administratè a pa kòrèk.'); end if;
 if length(trim(coalesce(p_name,'')))<2 or length(trim(coalesce(p_professor_code,'')))<4 then return jsonb_build_object('ok',false,'message','Non oswa kòd la pa valab.'); end if;
 if exists(select 1 from public.academy_professors where active and crypt(p_professor_code,access_code_hash)=access_code_hash) then return jsonb_build_object('ok',false,'message','Kòd sa deja itilize.'); end if;
 insert into public.academy_professors(full_name,phone,access_code_hash) values(trim(p_name),nullif(trim(p_phone),''),crypt(p_professor_code,gen_salt('bf')));
 return jsonb_build_object('ok',true,'message','Pwofesè a kreye.');
end $$;

create or replace function public.professor_get_data(p_professor_code text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare p public.academy_professors%rowtype;
begin
 select * into p from public.academy_professors where active and crypt(p_professor_code,access_code_hash)=access_code_hash limit 1;
 if not found then return jsonb_build_object('ok',false,'message','Kòd pwofesè a pa valab.'); end if;
 return jsonb_build_object(
 'ok',true,'professor',jsonb_build_object('id',p.id,'name',p.full_name),
 'courses',(select coalesce(jsonb_agg(jsonb_build_object('id',c.id,'slug',c.slug,'nom',c.nom,'price_htg',c.price_htg,'professor_id',c.professor_id) order by c.nom),'[]'::jsonb) from public.courses c),
 'students',(select coalesce(jsonb_agg(jsonb_build_object('id',s.id,'code',s.code,'nom',s.nom,'telephone',s.telephone) order by s.nom),'[]'::jsonb) from public.students s where s.created_by_professor_id=p.id),
 'sales',(select coalesce(jsonb_agg(jsonb_build_object('id',x.id,'student_code',x.student_code,'course_slug',x.course_slug,'sale_price_htg',x.sale_price_htg,'academy_share_htg',x.academy_share_htg,'professor_share_htg',x.professor_share_htg,'payment_status',x.payment_status,'created_at',x.created_at) order by x.created_at desc),'[]'::jsonb) from public.professor_sales x where x.professor_id=p.id),
 'messages',(select coalesce(jsonb_agg(jsonb_build_object('id',m.id,'message',m.message,'sender_role',m.sender_role,'created_at',m.created_at) order by m.created_at),'[]'::jsonb) from public.professor_messages m where m.professor_id=p.id),
 'requests',(select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'student_code',r.student_code,'course_slug',r.course_slug,'note',r.note,'status',r.status,'created_at',r.created_at) order by r.created_at desc),'[]'::jsonb) from public.professor_certificate_requests r where r.professor_id=p.id)
 );
end $$;

create or replace function public.professor_create_course(p_professor_code text,p_name text,p_slug text,p_price integer,p_description text default '')
returns jsonb language plpgsql security definer set search_path=public
as $$
declare p public.academy_professors%rowtype;
begin
 select * into p from public.academy_professors where active and crypt(p_professor_code,access_code_hash)=access_code_hash limit 1;
 if not found then return jsonb_build_object('ok',false,'message','Kòd pwofesè a pa valab.'); end if;
 if trim(coalesce(p_name,''))='' or trim(coalesce(p_slug,''))='' or coalesce(p_price,0)<1 then return jsonb_build_object('ok',false,'message','Ranpli non, slug ak pri kou a.'); end if;
 if exists(select 1 from public.courses where lower(slug)=lower(trim(p_slug))) then return jsonb_build_object('ok',false,'message','Kou sa deja egziste.'); end if;
 insert into public.courses(nom,slug,professor_id,price_htg) values(trim(p_name),lower(trim(p_slug)),p.id,p_price);
 return jsonb_build_object('ok',true,'message','Kou kreye.');
end $$;

create or replace function public.professor_create_lesson(p_professor_code text,p_course_slug text,p_title text,p_description text,p_content_type text,p_media_url text,p_sort_order integer default 1)
