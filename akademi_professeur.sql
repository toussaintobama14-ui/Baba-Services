create or replace function public.admin_professor_overview(p_admin_code text)
returns jsonb language plpgsql security definer set search_path=public
as $$
begin
 if not public._academy_admin_ok(p_admin_code) then return jsonb_build_object('ok',false,'message','Kòd administratè a pa kòrèk.'); end if;
 return jsonb_build_object(
 'ok',true,
 'professors',(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'full_name',p.full_name,'phone',p.phone,'active',p.active,'created_at',p.created_at) order by p.created_at desc),'[]'::jsonb) from public.academy_professors p),
 'sales',(select coalesce(jsonb_agg(jsonb_build_object('professor_id',s.professor_id,'professor_name',p.full_name,'student_code',s.student_code,'course_slug',s.course_slug,'sale_price_htg',s.sale_price_htg,'academy_share_htg',s.academy_share_htg,'professor_share_htg',s.professor_share_htg,'payment_status',s.payment_status,'created_at',s.created_at) order by s.created_at desc),'[]'::jsonb) from public.professor_sales s join public.academy_professors p on p.id=s.professor_id),
 'requests',(select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'professor_name',p.full_name,'student_code',r.student_code,'course_slug',r.course_slug,'note',r.note,'status',r.status,'created_at',r.created_at) order by r.created_at desc),'[]'::jsonb) from public.professor_certificate_requests r join public.academy_professors p on p.id=r.professor_id)
 );
end $$;

